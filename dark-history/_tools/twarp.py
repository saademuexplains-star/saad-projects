#!/usr/bin/env python3
"""The Coca-Cola time warp: the film was cut to the tight voice-over (every pause trimmed to 0.11 s, 47.32 s); the
user found those cuts rigid ("he ends one word and the other appears instantly"). The delivered voice is now the take
with its own pauses (0.15 - 0.46 s, 52.13 s). Every animation time stays as it was written (the "old" time, against
the tight voice); this module maps old time to the new timeline and back.

Each pause that the tight cut removed (delta seconds of the take) is put back by easing the picture through it: the
extra time is spread over the old pause and 0.3 s either side with a raised-cosine profile, so the animation slows a
little through the narrator's pause instead of stopping, and the words stay where they are (a word next to a pause
moves by at most a third of that pause).

  python3 -I _tools/twarp.py build      # writes _vo18/vo_nat.wav, _render/video/twarp_coca.js, prints the summary
"""
import os, sys, math, wave
import numpy as np

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
MAP = os.path.join(ROOT, '_vo18', 'vo_tight.wav.map.txt')
FPS = 60
SPREAD = 0.3          # s of old time either side of a pause the extra time is spread over
KEEP = 0.11           # the pause the tight cut left (s)
FRAMES = 3264         # 54.40 s: the voice ends at 52.13 s, the written name holds ~2 s, then the 0.5 s loop morph


def _rows():
    rows = []
    for ln in open(MAP):
        p = ln.split()
        if len(p) == 3:
            rows.append(tuple(float(x) for x in p))
    return rows


ROWS = _rows()
HEAD = ROWS[0][0]                       # the take is played from here (its first kept sample)
TAKE_END = ROWS[-1][1]
# (old boundary, extra seconds) for every pause the tight cut shortened
PAUSES = [(ROWS[i + 1][2], ROWS[i + 1][0] - ROWS[i][1]) for i in range(len(ROWS) - 1)]
TOTAL = sum(d for _, d in PAUSES)
OLD_END_VO = ROWS[-1][2] + ROWS[-1][1] - ROWS[-1][0]


def _cdf(u):
    u = min(1.0, max(0.0, u))
    return u - math.sin(2 * math.pi * u) / (2 * math.pi)


def fwd(t):
    """old time -> new time"""
    s = t
    for b, d in PAUSES:
        a0, w = b - KEEP / 2 - SPREAD, KEEP + 2 * SPREAD
        if t <= a0:
            break
        s += d * _cdf((t - a0) / w)
    return s


def inv(T):
    """new time -> old time (monotone; bisection)"""
    lo, hi = T - TOTAL - 1.0, T + 1.0
    for _ in range(60):
        m = (lo + hi) / 2
        if fwd(m) < T:
            lo = m
        else:
            hi = m
    return (lo + hi) / 2


def build():
    # the take with its own pauses, from the first kept sample to the end of the last, 6 ms fades at both ends
    src = os.path.join(ROOT, '_vo18', 'vo_hq.wav')
    with wave.open(src, 'rb') as w:
        ch, sw, sr, n = w.getnchannels(), w.getsampwidth(), w.getframerate(), w.getnframes()
        a = np.frombuffer(w.readframes(n), dtype='<i2').reshape(-1, ch).astype(np.float64)
    i0, i1 = int(round(HEAD * sr)), int(round(TAKE_END * sr))
    seg = a[i0:i1].copy()
    fd = int(0.006 * sr)
    seg[:fd] *= (np.arange(fd) / fd)[:, None]; seg[-fd:] *= (np.arange(fd, 0, -1) / fd)[:, None]
    out = os.path.join(ROOT, '_vo18', 'vo_nat.wav')
    with wave.open(out, 'wb') as w:
        w.setnchannels(ch); w.setsampwidth(2); w.setframerate(sr); w.writeframes(np.round(seg).astype('<i2').tobytes())
    # the old time of every frame (FRAMES + 1 entries: the last is the loop point)
    T = [inv(k / FPS) for k in range(FRAMES + 1)]
    js = os.path.join(ROOT, '_render', 'video', 'twarp_coca.js')
    with open(js, 'w') as f:
        f.write('// Generated by _tools/twarp.py - do not edit. The old (animation) time of every frame: the picture eases\n')
        f.write('// through the narrator\'s own pauses (the voice is the take with its pauses, _vo18/vo_nat.wav).\n')
        f.write(f'window.VIDEO_FRAMES = {FRAMES};\n')
        f.write('window.TWARP_T = [' + ','.join(f'{x:.5f}' for x in T) + '];\n')
    vo_len = len(seg) / sr
    print(f'pauses {len(PAUSES)}  extra {TOTAL:.3f}s  voice {vo_len:.3f}s (old end {OLD_END_VO:.3f} -> new {fwd(OLD_END_VO):.3f})')
    print(f'frames {FRAMES} = {FRAMES / FPS:.3f}s; old end {T[-1]:.4f}; slope range '
          f'{min(T[k + 1] - T[k] for k in range(FRAMES)) * FPS:.3f} .. {max(T[k + 1] - T[k] for k in range(FRAMES)) * FPS:.3f}')
    worst = max(abs(fwd(b - KEEP / 2) - (b - KEEP / 2) - sum(d for bb, d in PAUSES if bb < b)) for b, _ in PAUSES)
    print(f'largest word shift at a pause edge {worst:.3f}s')


if __name__ == '__main__':
    if len(sys.argv) > 1 and sys.argv[1] == 'build':
        build()
    else:
        print(__doc__)
